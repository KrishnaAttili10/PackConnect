BEGIN;
ALTER TABLE public.students ADD COLUMN IF NOT EXISTS session_version integer NOT NULL DEFAULT 0;
ALTER TABLE public.advice_requests ADD COLUMN IF NOT EXISTS expires_at timestamptz;
UPDATE public.advice_requests SET expires_at = created_at + interval '7 days' WHERE expires_at IS NULL;
ALTER TABLE public.advice_requests ALTER COLUMN expires_at SET DEFAULT (now() + interval '7 days');
ALTER TABLE public.advice_requests ALTER COLUMN expires_at SET NOT NULL;
ALTER TABLE public.advice_requests DROP CONSTRAINT IF EXISTS advice_requests_status_check;
ALTER TABLE public.advice_requests ADD CONSTRAINT advice_requests_status_check
 CHECK (status IN ('pending','accepted','declined','completed','cancelled','expired','closed'));
CREATE INDEX IF NOT EXISTS requests_expiration ON public.advice_requests (expires_at, recipient_id) WHERE status = 'pending';
ALTER TABLE public.notifications DROP CONSTRAINT IF EXISTS notifications_kind_check;
ALTER TABLE public.notifications ADD CONSTRAINT notifications_kind_check
 CHECK (kind IN ('request_received','accepted','declined','message','cancelled','expired','meeting'));
CREATE TABLE IF NOT EXISTS public.student_blocks (
 blocker_id bigint NOT NULL REFERENCES public.students(id), blocked_id bigint NOT NULL REFERENCES public.students(id),
 created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY (blocker_id,blocked_id), CHECK(blocker_id <> blocked_id)
);
CREATE INDEX IF NOT EXISTS blocks_reverse ON public.student_blocks(blocked_id,blocker_id);
CREATE TABLE IF NOT EXISTS public.conversation_reads (
 user_id bigint NOT NULL REFERENCES public.students(id), request_id bigint NOT NULL REFERENCES public.advice_requests(id),
 last_read_id bigint NOT NULL DEFAULT 0, PRIMARY KEY(user_id,request_id)
);
CREATE TABLE IF NOT EXISTS public.student_reports (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id bigint NOT NULL REFERENCES public.students(id), reported_id bigint NOT NULL REFERENCES public.students(id),
 message_id bigint REFERENCES public.chat_messages(id), reason text NOT NULL CHECK(length(reason) BETWEEN 1 AND 2000),
 status text NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved','dismissed')),
 reviewed_by bigint REFERENCES public.students(id), resolution text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(), CHECK(reporter_id <> reported_id)
);
CREATE TABLE IF NOT EXISTS public.staff_members (student_id bigint PRIMARY KEY REFERENCES public.students(id));
CREATE TABLE IF NOT EXISTS public.advice_meetings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id bigint NOT NULL REFERENCES public.advice_requests(id),
 proposer_id bigint NOT NULL REFERENCES public.students(id), starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
 location text NOT NULL CHECK(length(location) BETWEEN 1 AND 300),
 status text NOT NULL DEFAULT 'proposed' CHECK(status IN ('proposed','accepted','declined','cancelled')),
 created_at timestamptz NOT NULL DEFAULT now(), CHECK(ends_at > starts_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_meeting_proposal ON public.advice_meetings(request_id) WHERE status = 'proposed';
CREATE INDEX IF NOT EXISTS meetings_schedule ON public.advice_meetings(starts_at,ends_at) WHERE status = 'accepted';
CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
 token_hash text PRIMARY KEY, student_id bigint NOT NULL REFERENCES public.students(id),
 created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL, used_at timestamptz
);
CREATE INDEX IF NOT EXISTS reset_by_student ON public.password_reset_tokens(student_id,created_at);
CREATE TABLE IF NOT EXISTS public.recovery_limits (
 key_hash text PRIMARY KEY, window_start timestamptz NOT NULL DEFAULT now(), attempts integer NOT NULL DEFAULT 1
);
DO $$ DECLARE target text; seq text; BEGIN
 FOREACH target IN ARRAY ARRAY['student_blocks','conversation_reads','student_reports','staff_members','advice_meetings','password_reset_tokens','recovery_limits'] LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',target);
  EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated',target);
  EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO service_role',target);
  seq := NULL;
  IF target IN ('student_reports','advice_meetings') THEN
   seq := pg_get_serial_sequence('public.' || target,'id');
  END IF;
  IF seq IS NOT NULL THEN
   EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated',seq);
   EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO service_role',seq);
  END IF;
 END LOOP;
END $$;
NOTIFY pgrst,'reload schema';
COMMIT;
