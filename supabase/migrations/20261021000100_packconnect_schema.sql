-- Initial baseline. Existing dashboard-created tables are preserved.
-- Flask owns authorization; browser roles must not access these tables directly.
BEGIN;

CREATE TABLE IF NOT EXISTS public.students (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id uuid UNIQUE REFERENCES auth.users(id),
    name text NOT NULL,
    program text NOT NULL,
    year text NOT NULL,
    bio text NOT NULL DEFAULT '',
    interests text NOT NULL DEFAULT '',
    skills text NOT NULL DEFAULT '',
    advice_topics text NOT NULL DEFAULT '',
    willing_to_advise boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Retain Flask accounts until authentication is migrated separately.
CREATE TABLE IF NOT EXISTS public.accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL UNIQUE REFERENCES public.students(id),
    email text NOT NULL,
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS accounts_email_case_insensitive
    ON public.accounts (lower(email));

CREATE TABLE IF NOT EXISTS public.completed_courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(id),
    course_code text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.current_courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(id),
    course_code text NOT NULL
);
CREATE INDEX IF NOT EXISTS completed_courses_search
    ON public.completed_courses (course_code, student_id);
CREATE INDEX IF NOT EXISTS current_courses_student
    ON public.current_courses (student_id);

-- Legacy messages remain separate from accepted-request conversations.
CREATE TABLE IF NOT EXISTS public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL REFERENCES public.students(id),
    sender_user_id uuid REFERENCES auth.users(id),
    sender_name text NOT NULL,
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.advice_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id bigint NOT NULL REFERENCES public.students(id),
    recipient_id bigint NOT NULL REFERENCES public.students(id),
    course_code text NOT NULL,
    advice_topic text NOT NULL,
    message text NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'declined')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (sender_id <> recipient_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS active_advice_pair
    ON public.advice_requests
        (least(sender_id, recipient_id), greatest(sender_id, recipient_id))
    WHERE status IN ('pending', 'accepted');
CREATE TABLE IF NOT EXISTS public.chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES public.advice_requests(id),
    sender_id bigint NOT NULL REFERENCES public.students(id),
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS chat_request_cursor
    ON public.chat_messages (request_id, id);
CREATE TABLE IF NOT EXISTS public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.students(id),
    actor_id bigint NOT NULL REFERENCES public.students(id),
    request_id bigint NOT NULL REFERENCES public.advice_requests(id),
    kind text NOT NULL CHECK (kind IN ('request_received', 'accepted', 'declined', 'message')),
    event_key text NOT NULL UNIQUE,
    read_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notification_inbox
    ON public.notifications (user_id, id);

DO $$
DECLARE
    target text;
BEGIN
    FOREACH target IN ARRAY ARRAY[
        'students', 'accounts', 'completed_courses', 'current_courses',
        'messages', 'advice_requests', 'chat_messages', 'notifications'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', target);
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated', target);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO service_role', target);
        -- Only sequences belonging to PackConnect tables are changed.
        EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated',
            pg_get_serial_sequence('public.' || target, 'id'));
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role',
            pg_get_serial_sequence('public.' || target, 'id'));
    END LOOP;
END $$;

NOTIFY pgrst, 'reload schema';
COMMIT;
